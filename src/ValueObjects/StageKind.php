<?php

declare(strict_types=1);

namespace EugeneErg\Graphs\ValueObjects;

/**
 * Что именно произошло на шаге алгоритма.
 *
 * По виду шага отрисовка решает, как его показать: подсветить, развезти
 * куски по сторонам, вырезать ветви с дублями общих вершин или собрать всё
 * обратно.
 */
enum StageKind: string
{
    /** Исходный граф. */
    case Graph = 'graph';

    /** Одна волна заливки: что закрасилось на этом шаге. */
    case Fill = 'fill';

    /** Граф распался на несвязные куски. */
    case Components = 'components';

    /** Найдены точки сочленения. */
    case ArticulationVertexes = 'articulation';

    /**
     * Вершины заблокированы: краска через них не пройдёт.
     *
     * Это единственный приём, которым алгоритм вообще что-либо находит.
     * Заблокировать и залить — так он делит граф на несвязные куски (блокировать
     * нечего, заливка сама упирается в край), так вырезает двусвязные ветви
     * (блокируется точка сочленения) и так разбирает ветвь на поля (блокируется
     * весь обход). Показывать надо именно это: без блокировки на картинке
     * заливка останавливается непонятно почему.
     */
    case Block = 'block';

    /** Кусок разрезан на двусвязные ветви. */
    case Branches = 'branches';

    /**
     * Найдена очередная двусвязная ветвь: заливка от запертой точки сочленения
     * накрыла ровно её.
     */
    case Branch = 'branch';

    /**
     * Кусок, висящий на запертом обходе, оказался снаружи.
     *
     * Это и есть проверка планарности: каждый висящий кусок должен лечь либо
     * внутрь обхода, либо наружу, и два несовместимых внутрь не помещаются.
     * Признанное внешним уезжает на внешний круг — видно, что решили.
     */
    case Outside = 'outside';

    /** Из ветви вырезано очередное поле. */
    case Field = 'field';

    /**
     * Ветви связаны новой связью: две грани склеены в точке сочленения.
     * Связь искусственная — в самом графе её нет, — поэтому рисуется пунктиром.
     */
    case Tie = 'tie';

    /** В ветвях найдены грани плоской укладки. */
    case Faces = 'faces';

    /** Выбрана внешняя грань. */
    case OuterFace = 'outer';

    /** Определён порядок, в котором поля лягут на картинку. */
    case Order = 'order';

    /**
     * Поле легло легко: прилегает к границе участком, и его свободная
     * сторона легла дугой. В `highlight` — номера дуг, в `groups` — поле.
     */
    case Arc = 'arc';

    /**
     * Поле прилегает к границе одним ребром — дугу между соседями не
     * натянуть. Оно откладывается над этим ребром (`highlight`).
     */
    case Postpone = 'postpone';

    /**
     * Обычная дуга накрыла отложенное: оно ложится вместе с ней, а то, что
     * было внутри, раскладывается потом отдельно. В `highlight` — номера дуг,
     * в `groups` — поле дуги и отложенные поля.
     */
    case Absorb = 'absorb';

    /**
     * Укладывать больше нечего: отложенные поля виртуально объединяются
     * и ложатся одной дугой. В `highlight` — номера дуг, в `groups` — поля.
     */
    case Merge = 'merge';

    /** Очередное поле добавлено в строящуюся укладку. */
    case Build = 'build';

    /** Вершины поехали: расслабление. */
    case Relax = 'relax';

    /**
     * На шаге вершины меняют положение, поэтому отрисовка привязывает к нему
     * кадры укладки, а не одну неподвижную картинку.
     */
    public function isMoving(): bool
    {
        return $this === self::Relax;
    }
}
