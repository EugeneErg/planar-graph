<?php

declare(strict_types=1);

namespace EugeneErg\Graphs\ValueObjects\Script;

/**
 * Одно физическое действие над клубком шаров на палках.
 *
 * Действий ровно столько, сколько их есть в самом алгоритме: отделить,
 * разрезать, объединить, связать, закрасить, уложить. Каждое меняет клубок
 * ровно один раз, поэтому каждому достаётся ровно один кадр — и «сначала всё
 * выделилось, потом всё произошло» становится невыразимым.
 *
 * Координат действие не знает: оно говорит, что делают, а не где это рисуют.
 */
interface ActionInterface
{
    /**
     * Что делают — одной строкой, на человеческом языке.
     *
     * Инструкцию должно быть видно глазами: по ней проверяют порядок рассказа,
     * не заглядывая ни в кадры, ни в координаты.
     */
    public function describe(): string;

    /**
     * Вопрос это или ответ.
     *
     * Вопрос клубка не меняет: запереть, залить, обвести, вынести наружу —
     * всё это спрашивает «а что получится». Ответ меняет: отделить, разрезать,
     * объединить, связать, уложить.
     *
     * Различие нужно потому, что вопрос сам по себе ничего не значит. Если
     * показать запертый обход и не показать, что из этого вышло, на картинке
     * останется непонятно зачем запертый обход. Поэтому вопрос всегда едет
     * вместе со своим ответом — и выкидывается вместе с ним.
     */
    public function isQuestion(): bool;

    /**
     * Каких шаров действие касается.
     *
     * Нужно, чтобы понять, можно ли делать два действия одновременно: если
     * они трогают разные шары, можно; если одни и те же — нельзя, потому что
     * непонятно, кто из них что сделал.
     *
     * @return int[]
     */
    public function vertexes(): array;
}
