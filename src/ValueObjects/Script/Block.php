<?php

declare(strict_types=1);

namespace EugeneErg\Graphs\ValueObjects\Script;

/**
 * Запереть шары: краска через них не пройдёт.
 *
 * Это единственный приём, которым алгоритм вообще что-либо находит, и он один
 * и тот же на всех трёх уровнях:
 *
 * - несвязные куски: запирать нечего, заливка сама упирается в край;
 * - двусвязные ветви: запирается точка сочленения, и заливка из соседа
 *   накрывает ровно одну ветвь;
 * - поля: запирается весь обход, и заливка из каждого его соседа накрывает
 *   ровно один кусок, висящий на обходе, — по нему и видно, внутри он или
 *   снаружи.
 *
 * Поэтому запирание — отдельное действие со своим кадром. Без него заливка
 * на картинке останавливается непонятно почему, и вместо логики выходит
 * случайность.
 */
final readonly class Block implements ActionInterface
{
    /**
     * @param int[] $vertexes
     * @param bool $walk заперт целый обход, а не точка сочленения
     *
     * Разница не в том, сколько шаров заперли, а в том, о чём спрашивают.
     * Запирают точку сочленения — спрашивают «что на ней висит», и кусок
     * при этом лежит как лежал. Запирают обход — спрашивают «что внутри,
     * а что снаружи», и кусок на время разбирается по трём кругам: обход
     * на средний, вынесенное на внешний.
     *
     * Сказать это должно само действие. Пока отрисовка угадывала по длине
     * списка — «заперто больше двух, значит обход», — всё держалось на том,
     * что точку сочленения запирают по одной. Стоило запереть семь точек
     * сочленения сразу, по одной на каждый несвязный кусок, и куча сошла
     * за обход: с каждого стола по вершине уехало на средний круг непонятно
     * зачем, а остаток стал кривым.
     */
    public function __construct(public array $vertexes, public bool $walk = false)
    {
    }

    public function describe(): string
    {
        return ($this->walk ? 'запереть обход ' : 'запереть ') . implode(',', $this->vertexes);
    }

    public function isQuestion(): bool
    {
        return true;
    }

    /**
     * @return int[]
     */
    public function vertexes(): array
    {
        return $this->vertexes;
    }
}
