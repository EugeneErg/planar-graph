<?php

declare(strict_types=1);

namespace EugeneErg\Graphs\ValueObjects\Instruction;

/**
 * Одно действие инструкции: что делают, а не где.
 *
 * Координат здесь нет и быть не может. Действие называет вершины и рёбра
 * и говорит, что с ними происходит: заливают, запирают, вынимают,
 * раздваивают, склеивают, связывают. Где это лежит, решает геометрия,
 * сколько экземпляров и когда — отрисовка.
 */
interface ActionInterface
{
    /**
     * Действие одной строкой, так, чтобы читалось как конспект алгоритма.
     */
    public function describe(): string;
}
